import { exports } from "cloudflare:workers";
import { describe, expect, it } from "vitest";

const BASE = "https://exo.test";

const call = (path: string, init: RequestInit & { cookie?: string } = {}) => {
  const headers = new Headers(init.headers);
  if (init.method && init.method !== "GET") headers.set("x-exo", "1");
  if (init.cookie) headers.set("cookie", init.cookie);
  return exports.default.fetch(new Request(`${BASE}${path}`, { ...init, headers }));
};

const postJson = (path: string, body: unknown, cookie?: string) =>
  call(path, { method: "POST", body: JSON.stringify(body), headers: { "content-type": "application/json" }, cookie });

const signup = async (email = `u${crypto.randomUUID().slice(0, 8)}@exo.test`) => {
  const res = await postJson("/api/auth/signup", { email, password: "correct horse battery" });
  expect(res.status).toBe(201);
  const cookie = res.headers.get("set-cookie")!.split(";")[0]!;
  return { email, cookie };
};

describe("auth", () => {
  it("signs up, reads the session and logs out", async () => {
    const { email, cookie } = await signup();
    const me = await call("/api/me", { cookie });
    expect(await me.json()).toMatchObject({ user: { email } });

    await call("/api/auth/logout", { method: "POST", cookie });
    const after = await call("/api/me", { cookie });
    expect(await after.json()).toEqual({ user: null });
  });

  it("rejects duplicate emails and wrong passwords with stable codes", async () => {
    const { email } = await signup();
    const dup = await postJson("/api/auth/signup", { email, password: "another password" });
    expect(dup.status).toBe(409);
    expect(await dup.json()).toMatchObject({ code: "ERR_CONFLICT" });

    const bad = await postJson("/api/auth/login", { email, password: "wrong password!" });
    expect(bad.status).toBe(401);
    expect(await bad.json()).toMatchObject({ code: "ERR_UNAUTHORIZED", error: "Wrong email or password." });
  });

  it("validates input with Schema", async () => {
    const res = await postJson("/api/auth/signup", { email: "not-an-email", password: "short" });
    expect(res.status).toBe(400);
    expect(await res.json()).toMatchObject({ code: "ERR_BAD_REQUEST" });
  });

  it("blocks mutating requests without the CSRF header", async () => {
    const res = await exports.default.fetch(
      new Request(`${BASE}/api/auth/signup`, {
        method: "POST",
        body: "{}",
        headers: { "content-type": "application/json" },
      }),
    );
    expect(res.status).toBe(403);
  });
});

describe("projects, files and renders", () => {
  it("creates a project, uploads G-code, saves a render and cleans up", async () => {
    const { cookie } = await signup();
    const created = await postJson("/api/projects", { name: "Lamp" }, cookie);
    expect(created.status).toBe(201);
    const { project } = (await created.json()) as { project: { id: string } };

    const gcode = "; generated by BambuStudio\n;LAYER_CHANGE\nG1 X1 Y1 E1\n";
    const upload = await call(`/api/projects/${project.id}/files?name=lamp.gcode`, {
      method: "PUT",
      body: gcode,
      headers: { "content-length": String(gcode.length) },
      cookie,
    });
    expect(upload.status).toBe(201);
    const { file } = (await upload.json()) as { file: { url: string } };
    const download = await call(file.url, { cookie });
    expect(await download.text()).toBe(gcode);

    const stl = await call(`/api/projects/${project.id}/files?name=lamp.stl`, { method: "PUT", body: "x", cookie });
    expect(stl.status).toBe(400);
    expect(((await stl.json()) as { error: string }).error).toMatch(/Slice it first/);

    const meta = encodeURIComponent(
      JSON.stringify({
        kind: "image",
        label: "Lamp hero",
        projectId: project.id,
        width: 2000,
        height: 2000,
        platform: "amazon",
      }),
    );
    const png = new Uint8Array([137, 80, 78, 71, 13, 10, 26, 10]);
    const saved = await call(`/api/renders?meta=${meta}`, {
      method: "POST",
      body: png,
      headers: { "content-type": "image/png", "content-length": String(png.length) },
      cookie,
    });
    expect(saved.status).toBe(201);

    const list = (await (await call(`/api/renders?projectId=${project.id}`, { cookie })).json()) as {
      renders: Array<{ label: string; url: string; meta: { platform: string } }>;
    };
    expect(list.renders).toHaveLength(1);
    expect(list.renders[0]).toMatchObject({ label: "Lamp hero", meta: { platform: "amazon" } });

    const del = await call(`/api/projects/${project.id}`, { method: "DELETE", cookie });
    expect(del.status).toBe(200);
    const gallery = (await (await call("/api/renders", { cookie })).json()) as { renders: unknown[] };
    expect(gallery.renders).toHaveLength(1);
  });

  it("never exposes another user's project", async () => {
    const a = await signup();
    const b = await signup();
    const { project } = (await (await postJson("/api/projects", { name: "Private" }, a.cookie)).json()) as {
      project: { id: string };
    };
    const res = await call(`/api/projects/${project.id}`, { cookie: b.cookie });
    expect(res.status).toBe(404);
  });
});
