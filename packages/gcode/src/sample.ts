// Procedural sample prints, emitted as real Bambu-style G-code so the whole pipeline
// (parse -> mesh -> render) runs on them exactly as on an uploaded file.

export interface RevolvedSpec {
  name: string;
  height: number;
  layerHeight: number;
  /** Outer radius (mm) at height z and angle theta. */
  radius: (z: number, theta: number) => number;
  walls: number;
  bottomLayers: number;
  lineWidth: number;
  color: string;
  /** Bed center (Bambu A1/P1/X1 plates are 256 x 256). */
  center?: [number, number];
}

const fmt = (n: number) => n.toFixed(3).replace(/\.?0+$/, "");

export const generateRevolvedGcode = (spec: RevolvedSpec): string => {
  const [bx, by] = spec.center ?? [128, 128];
  const filamentArea = Math.PI * (1.75 / 2) ** 2;
  const out: string[] = [
    "; HEADER_BLOCK_START",
    "; generated by BambuStudio 02.02.00.85",
    `; model: ${spec.name}`,
    "; HEADER_BLOCK_END",
    "; CONFIG_BLOCK_START",
    `; layer_height = ${spec.layerHeight}`,
    "; nozzle_diameter = 0.4",
    "; filament_diameter = 1.75",
    `; filament_colour = ${spec.color}`,
    "; CONFIG_BLOCK_END",
    "G90",
    "M83",
    "T0",
    // Purge line before the first layer marker: must be dropped by the parser.
    "G1 X18 Y1 Z0.3 F6000",
    "G1 X240 Y1 E20 F1200",
  ];
  const layers = Math.round(spec.height / spec.layerHeight);
  const bead = (w: number, h: number, len: number) => (((w - h) * h + Math.PI * (h / 2) ** 2) * len) / filamentArea;

  for (let L = 0; L < layers; L++) {
    const z = (L + 1) * spec.layerHeight;
    out.push("; CHANGE_LAYER", `; Z_HEIGHT: ${fmt(z)}`, `; LAYER_HEIGHT: ${spec.layerHeight}`);
    for (let wall = spec.walls - 1; wall >= 0; wall--) {
      out.push(`; FEATURE: ${wall === 0 ? "Outer wall" : "Inner wall"}`, `; LINE_WIDTH: ${spec.lineWidth}`);
      const inset = wall * spec.lineWidth * 0.9 + spec.lineWidth / 2;
      const r0 = spec.radius(z, 0) - inset;
      const steps = Math.max(48, Math.round((Math.PI * 2 * r0) / 0.6));
      let px = bx + r0;
      let py = by;
      out.push(`G1 X${fmt(px)} Y${fmt(py)} Z${fmt(z)} F12000`);
      for (let s = 1; s <= steps; s++) {
        const th = (s / steps) * Math.PI * 2;
        const r = spec.radius(z, th) - inset;
        const nx = bx + r * Math.cos(th);
        const ny = by + r * Math.sin(th);
        const len = Math.hypot(nx - px, ny - py);
        out.push(`G1 X${fmt(nx)} Y${fmt(ny)} E${fmt(bead(spec.lineWidth, spec.layerHeight, len))} F3000`);
        px = nx;
        py = ny;
      }
    }
    if (L < spec.bottomLayers) {
      out.push(
        `; FEATURE: ${L === 0 ? "Bottom surface" : L === spec.bottomLayers - 1 ? "Top surface" : "Internal solid infill"}`,
      );
      const rMax = spec.radius(z, 0) - spec.walls * spec.lineWidth;
      for (let r = rMax; r > spec.lineWidth; r -= spec.lineWidth) {
        const steps = Math.max(24, Math.round((Math.PI * 2 * r) / 0.8));
        out.push(`G1 X${fmt(bx + r)} Y${fmt(by)} F12000`);
        let px = bx + r;
        let py = by;
        for (let s = 1; s <= steps; s++) {
          const th = (s / steps) * Math.PI * 2;
          const nx = bx + r * Math.cos(th);
          const ny = by + r * Math.sin(th);
          out.push(
            `G1 X${fmt(nx)} Y${fmt(ny)} E${fmt(bead(spec.lineWidth, spec.layerHeight, Math.hypot(nx - px, ny - py)))} F3000`,
          );
          px = nx;
          py = ny;
        }
      }
    }
  }
  out.push("; FEATURE: Custom", "G1 Z" + fmt(spec.height + 10) + " F600", "M400");
  return out.join("\n");
};

/** A ribbed, twisting lamp shade: shows off layer lines and silk sheen. */
export const SAMPLE_LAMP: RevolvedSpec = {
  name: "Ribbed lamp",
  height: 90,
  layerHeight: 0.24,
  walls: 2,
  bottomLayers: 3,
  lineWidth: 0.45,
  color: "#d79a88",
  radius: (z, th) => {
    const t = z / 90;
    const body = 34 + 9 * Math.sin(Math.PI * (t * 0.9 + 0.05)) - 6 * t;
    return body + 1.4 * Math.cos(18 * th + t * 2.4);
  },
};

